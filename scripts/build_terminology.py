"""Generate the draft ConceptMaps and the review table from the candidate list.

mappings/terminology-candidates.csv is the single source. This script writes:
  ig/input/fsh/conceptmaps.fsh                       two ConceptMap instances
  ig/input/includes/terminology-candidates-table.md   review table for the IG page

Every candidate code in the CSV was looked up on tx.fhir.org (see the
verified_with column); scripts/verify_terminology.py repeats that check.
Existence of a code is verified; whether it is the right mapping is a clinical
and terminology judgement recorded in review_status, and stays "unreviewed"
until a reviewer signs it off.

Run from the repository root:  python3 scripts/build_terminology.py
"""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CANON = "https://healthymind-tech.github.io/ntucc-fhir-colorectal-cancer-ig"
CSV_PATH = ROOT / "mappings/terminology-candidates.csv"
FSH_PATH = ROOT / "ig/input/fsh/conceptmaps.fsh"
TABLE_PATH = ROOT / "ig/input/includes/terminology-candidates-table.md"

TARGET_SYSTEMS = {"http://loinc.org", "http://snomed.info/sct"}
EQUIVALENCES = {"equivalent", "wider", "narrower", "relatedto", "inexact", "unmatched"}
REVIEW_STATES = {"unreviewed", "accepted", "rejected"}

MAPS = {
    "tcr-field-to-loinc": {
        "instance": "CRCTCRFieldToLOINC",
        "title": "癌登欄位 → LOINC（候選，待審核）",
        "description": "大腸癌核心指標引用之癌登長表欄位與 LOINC 觀察碼的候選對應。代碼存在性已以 tx.fhir.org 查證；對應是否正確尚待術語與臨床審核，未審核前不得用於正式交換。",
        "source": f"{CANON}/CodeSystem/crc-tcr-field",
    },
    "indicator-concept-to-standard": {
        "instance": "CRCIndicatorConceptToStandard",
        "title": "指標 1 本地概念 → SNOMED CT／LOINC（候選，待審核）",
        "description": "指標 1 本地暫用概念代碼與 SNOMED CT、LOINC 的候選對應。代碼存在性已以 tx.fhir.org 查證；對應是否正確尚待術語與臨床審核，未審核前不得用於正式交換。",
        "source": f"{CANON}/CodeSystem/crc-indicator-concept",
    },
}
UNMATCHED_TARGET = {"tcr-field-to-loinc": "http://loinc.org", "indicator-concept-to-standard": "http://snomed.info/sct"}


def load_rows() -> list[dict[str, str]]:
    with CSV_PATH.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    seen: set[tuple[str, str, str]] = set()
    displays: dict[tuple[str, str], str] = {}
    for row in rows:
        for key, value in row.items():
            if value != value.strip():
                raise SystemExit(f"{row['source_code']}: leading/trailing whitespace in {key}")
        identity = (row["map_id"], row["source_code"], row["target_code"])
        if identity in seen:
            raise SystemExit(f"duplicate candidate row {identity}")
        seen.add(identity)
        previous = displays.setdefault((row["map_id"], row["source_code"]), row["source_display"])
        if previous != row["source_display"]:
            raise SystemExit(f"{row['source_code']}: source_display differs between rows")
        if row["target_system"] and row["target_system"] not in TARGET_SYSTEMS:
            raise SystemExit(f"{row['source_code']}: unknown target_system {row['target_system']}")
        if row["map_id"] not in MAPS:
            raise SystemExit(f"unknown map_id {row['map_id']}")
        if row["equivalence"] not in EQUIVALENCES:
            raise SystemExit(f"{row['source_code']}: bad equivalence {row['equivalence']}")
        if row["review_status"] not in REVIEW_STATES:
            raise SystemExit(f"{row['source_code']}: bad review_status {row['review_status']}")
        if (row["equivalence"] == "unmatched") != (row["target_code"] == ""):
            raise SystemExit(f"{row['source_code']}: unmatched rows must have no target, others must have one")
    return rows


def fsh_string(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def build_fsh(rows: list[dict[str, str]]) -> str:
    out = [
        "// GENERATED by scripts/build_terminology.py from mappings/terminology-candidates.csv.",
        "// Do not edit by hand.",
        "",
    ]
    for map_id, meta in MAPS.items():
        groups: dict[str, dict[str, list[dict[str, str]]]] = defaultdict(lambda: defaultdict(list))
        for row in rows:
            # Rejected candidates stay in the review table for traceability but
            # are never published as a mapping.
            if row["map_id"] == map_id and row["review_status"] != "rejected":
                target = row["target_system"] or UNMATCHED_TARGET[map_id]
                groups[target][row["source_code"]].append(row)
        out += [
            f"Instance: {meta['instance']}",
            "InstanceOf: ConceptMap",
            "Usage: #definition",
            f'Title: "{fsh_string(meta["title"])}"',
            f'Description: "{fsh_string(meta["description"])}"',
            f'* id = "{map_id}"',
            f'* url = "{CANON}/ConceptMap/{map_id}"',
            f'* name = "{meta["instance"]}"',
            "* language = #zh-TW",
            '* version = "0.1.0-preview.2"',
            "* status = #draft",
            "* experimental = true",
        ]
        for g, (target, elements) in enumerate(groups.items()):
            out += [f'* group[{g}].source = "{meta["source"]}"', f'* group[{g}].target = "{target}"']
            for e, (code, items) in enumerate(elements.items()):
                prefix = f"* group[{g}].element[{e}]"
                out += [f"{prefix}.code = #{code}", f'{prefix}.display = "{fsh_string(items[0]["source_display"])}"']
                for t, row in enumerate(items):
                    tp = f"{prefix}.target[{t}]"
                    comment = f"[{row['review_status']}] {row['rationale']}"
                    if row["target_code"]:
                        out += [f"{tp}.code = #{row['target_code']}", f'{tp}.display = "{fsh_string(row["target_display"])}"']
                    out += [
                        f"{tp}.equivalence = #{row['equivalence']}",
                        f'{tp}.comment = "{fsh_string(comment)}"',
                    ]
        out.append("")
    return "\n".join(out)


def build_table(rows: list[dict[str, str]]) -> str:
    lines = [
        "<!-- GENERATED by scripts/build_terminology.py from mappings/terminology-candidates.csv. Do not edit by hand. -->",
        "",
        "| 對應 | 來源代碼 | 來源概念 | 候選代碼 | 候選名稱（官方 display） | 類型 | 關係 | 理由 | 審核狀態 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        system = {"http://loinc.org": "LOINC", "http://snomed.info/sct": "SNOMED CT"}.get(row["target_system"], "")
        code = f"{system} `{row['target_code']}`" if row["target_code"] else "—"
        lines.append(
            f"| {row['map_id']} | `{row['source_code']}` | {row['source_display']} | {code} | "
            f"{row['target_display'] or '—'} | {row['target_kind'] or '—'} | {row['equivalence']} | "
            f"{row['rationale']} | {row['review_status']} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    rows = load_rows()
    FSH_PATH.write_text(build_fsh(rows), encoding="utf-8")
    TABLE_PATH.write_text(build_table(rows), encoding="utf-8")
    print(f"{len(rows)} candidate rows -> {FSH_PATH.relative_to(ROOT)}, {TABLE_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
